def link_success(schedule: str) -> str:
    """Confirmation shown after a web account connects to the bot."""
    lines = [
        "🔗 Аккаунт с сайта подключён!",
        "",
        "Твой профиль и программа уже здесь.",
    ]
    if schedule:
        lines.append(f"Напоминания о тренировках: <b>{schedule}</b>.")
    else:
        lines.append("Напоминания можно включить командой /reminders.")
    return "\n".join(lines)


def paywall(price: int, days: int) -> str:
    """Full paywall screen listing what Pro unlocks."""
    lines = [PAYWALL_HEADER, "Что открывается:"]
    for _, label in PRO_FEATURE_LABELS:
        lines.append(f"• {label}")
    lines.append(PAYWALL_FOOTER.format(price=price, days=days))
    return "\n".join(lines)


def pro_only(feature: str, price: int, days: int) -> str:
    """Short paywall shown when a free user taps a Pro feature."""
    teaser = PRO_TEASERS.get(feature, "Расширенные возможности тренера.")
    return PRO_ONLY.format(teaser=teaser, price=price, days=days)


